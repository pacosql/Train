// Banco de palabras — primera tanda (~220 palabras) de las "1000 primeras
// palabras" para 1º de ESO, nivel Cambridge A1-A2 (Starters/Movers/Flyers
// y A2 Key). Igual que Math Games creció en tandas (#1-20, #21-40...),
// este banco crecerá en tandas sucesivas hasta acercarse a 1000 — esta
// primera cubre las categorías básicas que Cambridge examina primero:
// familia, cuerpo, ropa, comida, animales, colores, números, cole, casa,
// verbos de rutina diaria, adjetivos comunes, tiempo atmosférico, trabajos,
// sitios de la ciudad y tiempo/calendario.
//
// `related` enlaza palabras que se usan juntas en una frase real (p.ej.
// "scarf" -> "neck": me pongo la bufanda en el cuello) — lo usan los
// juegos #13 (Viste la escena) y #14 (La cadena de la escena) para
// reforzar varias palabras relacionadas en una sola pantalla, en vez de
// una suelta.
function w(en, es, emoji, cat, level, ex, exEs, related = [], idOverride = null) {
  const id = idOverride || en.toLowerCase().replace(/[^a-z0-9]+/g, "-");
  return { id, en, es, emoji, cat, level, ex, exEs, related };
}

